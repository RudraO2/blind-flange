# ------------------------------------------------------------------- rasterising


def rasterise(pdf_path: pathlib.Path, dpi: int) -> list[np.ndarray]:
    """Render every page of the clean PDF to a greyscale array."""
    document = pdfium.PdfDocument(str(pdf_path))
    try:
        pages = []
        for index in range(len(document)):
            bitmap = document[index].render(scale=dpi / 72.0, grayscale=True)
            pages.append(np.asarray(bitmap.to_numpy(), dtype=np.uint8).squeeze())
        return pages
    finally:
        document.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dpi", type=int, default=300, help="raster resolution, default 300")
    parser.add_argument("--seed", type=int, default=26117, help="RNG seed, default 26117")
    parser.add_argument(
        "--out-dir",
        type=pathlib.Path,
        default=pathlib.Path(__file__).parent,
        help="where the sample is written, default alongside this script",
    )
    arguments = parser.parse_args()

    rng = np.random.default_rng(arguments.seed)
    arguments.out_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as workspace:
        clean = pathlib.Path(workspace) / "clean.pdf"
        compose(clean, rng)
        rendered = rasterise(clean, arguments.dpi)

    # Skew carries a floor as well as a ceiling. A page that happens to draw an
    # angle near zero is a clean render again, and the whole point of the fixture
    # is that it is not one.
    scanned = [
        scan_artefacts.scan(
            page,
            rng,
            degrees=float(rng.choice([-1.0, 1.0]) * rng.uniform(0.35, 0.95)),
            radius=max(1, round(arguments.dpi / 260)),
        )
        for page in rendered
    ]

    for number, page in enumerate(scanned, start=1):
        target = arguments.out_dir / f"sample-inspection-report-p{number}.png"
        scan_artefacts.write_png(target, page, arguments.dpi)
        print(f"wrote {target.name}  {page.shape[1]}x{page.shape[0]} px")

    pdf_target = arguments.out_dir / "sample-inspection-report.pdf"
    scan_artefacts.write_scan_pdf(pdf_target, scanned, arguments.dpi)
    print(f"wrote {pdf_target.name}  {len(scanned)} pages, image only, no text layer")


if __name__ == "__main__":
    main()
