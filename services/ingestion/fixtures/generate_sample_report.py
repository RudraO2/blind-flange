"""Generate the synthetic scanned inspection report the ingestion stories run against.

Everything in the document is invented. Northcape Refining Company does not exist,
neither does Ravensfell Refinery, and the equipment tags and personnel are made up.
The page says so on itself, in the banner and in the footer, so the sample cannot be
mistaken for a real record belonging to MRPL or to anyone else.

The clean page is composed with ReportLab, rasterised with pypdfium2, then put
through ``scan_artefacts`` so it carries skew, speckle, uneven contrast and softened
edges. A clean render makes OCR look easier than it is, and Story 4.2 has to measure
Tesseract against something honest.

Run it with::

    python services/ingestion/fixtures/generate_sample_report.py

Output is deterministic for a given seed, so re-running it reproduces the committed
files byte for byte.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import tempfile

import numpy as np
import pypdfium2 as pdfium
from reportlab.lib.colors import Color
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

import scan_artefacts

PAGE_WIDTH, PAGE_HEIGHT = A4
MARGIN = 46.0

BODY = "Helvetica"
BODY_BOLD = "Helvetica-Bold"
HAND = "Times-Italic"

INK_PRINT = Color(0.08, 0.08, 0.09)
INK_FAINT = Color(0.38, 0.38, 0.40)
INK_PEN = Color(0.10, 0.16, 0.48)
RULE = Color(0.45, 0.45, 0.47)
HEADER_FILL = Color(0.88, 0.88, 0.89)

BANNER = (
    "SYNTHETIC SAMPLE — FICTIONAL COMPANY, PLANT, TAGS AND PERSONNEL — "
    "NOT A REAL INSPECTION RECORD"
)
FOOTER = (
    "Synthetic sample data. Northcape Refining Company and Ravensfell Refinery do not "
    "exist. Generated by services/ingestion/fixtures/generate_sample_report.py"
)


# --------------------------------------------------------------------------- text


def wrap(text: str, font: str, size: float, width: float, drawing: canvas.Canvas) -> list[str]:
    """Greedy word wrap against the real glyph widths of the chosen font."""
    lines: list[str] = []
    line = ""
    for word in text.split():
        candidate = f"{line} {word}".strip()
        if drawing.stringWidth(candidate, font, size) <= width or not line:
            line = candidate
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def paragraph(
    drawing: canvas.Canvas, x: float, y: float, text: str, width: float, size: float = 9.0
) -> float:
    drawing.setFont(BODY, size)
    drawing.setFillColor(INK_PRINT)
    leading = size * 1.42
    for line in wrap(text, BODY, size, width, drawing):
        drawing.drawString(x, y, line)
        y -= leading
    return y


def heading(drawing: canvas.Canvas, x: float, y: float, text: str) -> float:
    drawing.setFont(BODY_BOLD, 9.8)
    drawing.setFillColor(INK_PRINT)
    drawing.drawString(x, y, text)
    return y - 15.0


# -------------------------------------------------------------------------- table


def table(
    drawing: canvas.Canvas,
    x: float,
    y: float,
    widths: list[float],
    rows: list[list[str]],
    size: float = 7.9,
) -> tuple[float, list[tuple[float, float]]]:
    """Draw a ruled table with a bold header row.

    The first row is the header. Cells wrap, and the row grows to fit the tallest
    cell in it. Returns the new baseline and the top and bottom of every row, so a
    pen mark can be anchored to a cell that actually exists rather than to a
    guessed coordinate.
    """
    leading = size * 1.32
    pad_x, pad_y = 4.0, 4.5
    drawing.setLineWidth(0.5)
    bounds: list[tuple[float, float]] = []

    for index, row in enumerate(rows):
        header = index == 0
        font = BODY_BOLD if header else BODY
        wrapped = [
            wrap(str(cell), font, size, width - 2 * pad_x, drawing)
            for cell, width in zip(row, widths)
        ]
        height = max(len(cell) for cell in wrapped) * leading + 2 * pad_y

        if header:
            drawing.setFillColor(HEADER_FILL)
            drawing.rect(x, y - height, sum(widths), height, stroke=0, fill=1)

        drawing.setStrokeColor(RULE)
        drawing.rect(x, y - height, sum(widths), height, stroke=1, fill=0)
        edge = x
        for width in widths[:-1]:
            edge += width
            drawing.line(edge, y - height, edge, y)

        drawing.setFillColor(INK_PRINT)
        drawing.setFont(font, size)
        cell_x = x
        for lines, width in zip(wrapped, widths):
            text_y = y - pad_y - size
            for line in lines:
                drawing.drawString(cell_x + pad_x, text_y, line)
                text_y -= leading
            cell_x += width
        bounds.append((y, y - height))
        y -= height

    return y, bounds


# ---------------------------------------------------------------------- pen marks


def hand_text(
    drawing: canvas.Canvas,
    x: float,
    y: float,
    text: str,
    rng: np.random.Generator,
    size: float = 11.0,
) -> float:
    """Write a line the way a pen does — off the baseline, off the vertical.

    Each glyph is placed on its own rotation and baseline offset. It is a
    simulation of handwriting, not a scan of any, and the fixture README says so.
    """
    drawing.setFillColor(INK_PEN)
    cursor = x
    for character in text:
        if character == " ":
            cursor += size * 0.27
            continue
        glyph_size = size * float(rng.uniform(0.90, 1.10))
        drawing.saveState()
        drawing.translate(cursor, y + float(rng.uniform(-1.1, 1.1)))
        drawing.rotate(float(rng.uniform(-8.0, 8.0)))
        drawing.setFont(HAND, glyph_size)
        drawing.setFillColor(INK_PEN)
        drawing.drawString(0, 0, character)
        drawing.restoreState()
        cursor += drawing.stringWidth(character, HAND, glyph_size) * 0.93 + float(
            rng.uniform(-0.4, 0.7)
        )
    return cursor


def pen_stroke(
    drawing: canvas.Canvas,
    points: list[tuple[float, float]],
    rng: np.random.Generator,
    width: float = 1.15,
) -> None:
    """Join points with a wobbly bezier path, as a pen laid down in one motion."""
    drawing.saveState()
    drawing.setStrokeColor(INK_PEN)
    drawing.setLineWidth(width)
    path = drawing.beginPath()
    path.moveTo(*points[0])
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        # Wobble in proportion to the segment, so a long lead line bows gently and a
        # short one around a loop does not turn into a scallop.
        span = max(6.0, math.hypot(x1 - x0, y1 - y0)) * 0.10
        jitter = lambda: float(rng.uniform(-span, span))  # noqa: E731 - local shorthand
        path.curveTo(
            x0 + (x1 - x0) / 3 + jitter(),
            y0 + (y1 - y0) / 3 + jitter(),
            x0 + 2 * (x1 - x0) / 3 + jitter(),
            y0 + 2 * (y1 - y0) / 3 + jitter(),
            x1,
            y1,
        )
    drawing.drawPath(path, stroke=1, fill=0)
    drawing.restoreState()


def pen_ring(
    drawing: canvas.Canvas,
    centre_x: float,
    centre_y: float,
    radius_x: float,
    radius_y: float,
    rng: np.random.Generator,
) -> None:
    """Ring something on the page, overshooting the way a real circling does."""
    steps = 11
    points = []
    for step in range(steps + 3):
        angle = 2 * np.pi * step / steps
        points.append(
            (
                centre_x + radius_x * float(np.cos(angle)) + float(rng.uniform(-0.7, 0.7)),
                centre_y + radius_y * float(np.sin(angle)) + float(rng.uniform(-0.7, 0.7)),
            )
        )
    pen_stroke(drawing, points, rng, width=1.05)


def pen_signature(
    drawing: canvas.Canvas, x: float, y: float, width: float, rng: np.random.Generator
) -> None:
    """A signature drawn as one continuous cursive stroke.

    Two sine components give the rise and fall of the loops; a third, applied to
    the horizontal, makes the pen briefly travel backwards, which is what makes a
    signature cross itself instead of reading as a row of tent poles.
    """
    samples = 90
    rise_phase, loop_phase, back_phase = rng.uniform(0, 2 * np.pi, size=3)
    rise_rate = float(rng.uniform(2.0, 3.0))
    loop_rate = float(rng.uniform(4.5, 6.5))

    drawing.saveState()
    drawing.setStrokeColor(INK_PEN)
    drawing.setLineWidth(1.35)
    path = drawing.beginPath()
    for index in range(samples):
        t = index / (samples - 1)
        travel = width * (t + 0.05 * float(np.sin(2 * np.pi * 3 * t + back_phase)))
        height = (
            13.0 * float(np.sin(2 * np.pi * rise_rate * t + rise_phase))
            + 6.0 * float(np.sin(2 * np.pi * loop_rate * t + loop_phase))
            + 9.0 * t
        )
        point = (x + travel, y + height + float(rng.uniform(-0.5, 0.5)))
        if index == 0:
            path.moveTo(*point)
        else:
            path.lineTo(*point)
    drawing.drawPath(path, stroke=1, fill=0)
    drawing.restoreState()


# --------------------------------------------------------------------- page frame


def frame(drawing: canvas.Canvas, page_number: int, page_count: int) -> None:
    drawing.setFont(BODY_BOLD, 7.4)
    drawing.setFillColor(INK_FAINT)
    drawing.drawCentredString(PAGE_WIDTH / 2, PAGE_HEIGHT - 26, BANNER)
    drawing.setStrokeColor(RULE)
    drawing.setLineWidth(0.6)
    drawing.line(MARGIN, PAGE_HEIGHT - 33, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 33)

    drawing.setFont(BODY, 6.6)
    drawing.setFillColor(INK_FAINT)
    drawing.drawString(MARGIN, 28, FOOTER)
    drawing.drawRightString(PAGE_WIDTH - MARGIN, 28, f"Page {page_number} of {page_count}")
    drawing.line(MARGIN, 38, PAGE_WIDTH - MARGIN, 38)


def letterhead(drawing: canvas.Canvas, y: float) -> float:
    drawing.setFont(BODY_BOLD, 15.0)
    drawing.setFillColor(INK_PRINT)
    drawing.drawString(MARGIN, y, "NORTHCAPE REFINING COMPANY (FICTIONAL)")
    y -= 14
    drawing.setFont(BODY, 8.6)
    drawing.setFillColor(INK_FAINT)
    drawing.drawString(MARGIN, y, "Ravensfell Refinery · Unit 22, Crude Distillation · Mechanical Integrity Department")
    y -= 16
    drawing.setStrokeColor(INK_PRINT)
    drawing.setLineWidth(1.1)
    drawing.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
    return y - 22


def meta_block(drawing: canvas.Canvas, y: float, entries: list[tuple[str, str]]) -> float:
    """Two columns of label/value pairs, the way a report titleblock reads."""
    column_width = (PAGE_WIDTH - 2 * MARGIN) / 2
    start_y = y
    for index, (label, value) in enumerate(entries):
        column = index % 2
        row = index // 2
        x = MARGIN + column * column_width
        line_y = start_y - row * 13.5
        drawing.setFont(BODY_BOLD, 8.0)
        drawing.setFillColor(INK_FAINT)
        drawing.drawString(x, line_y, label)
        drawing.setFont(BODY, 8.6)
        drawing.setFillColor(INK_PRINT)
        drawing.drawString(x + 82, line_y, value)
    rows = (len(entries) + 1) // 2
    return start_y - rows * 13.5 - 10


